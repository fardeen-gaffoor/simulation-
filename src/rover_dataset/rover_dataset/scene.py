"""Per-scene environment randomization.

A *scene* is one generated world plus one generated rover.  Its randomization is
a pure function of ``(master_seed, scene_index)``: the same seed always writes
byte-identical ``arena.yaml`` / ``rover.yaml`` overrides, so any scene can be
regenerated and audited later.

What is randomized per scene (all of it visible in the images):

* **sand colour** -- hue rotation + brightness scale on ``arena.sand_color``,
* **lighting** -- sun elevation/azimuth, warm/cool diffuse tint, intensity and
  whether shadows are cast (``arena.light``),
* **shadows/ambient** -- ``arena.scene.ambient``, ``arena.scene.background`` and
  ``arena.light.cast_shadows``,
* **sand ripples** -- ``terrain.noise_amplitude``,
* **camera mounting** -- a small translation/rotation jitter per camera in
  ``rover.yaml``.  The calibration generated for the scene reflects the jitter,
  so labels are always computed with the pose the images were rendered with.

Blur and noise are per-frame (see :mod:`rover_dataset.augment`) rather than
per-scene, because they are sensor properties and change frame to frame.

The scene config is *written* here; the world and the rover are generated by the
existing module-1 / module-2 generators when the collection launch runs.
"""

