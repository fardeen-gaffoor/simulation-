def _share_dir(package: str) -> Optional[str]:
    try:
        from ament_index_python.packages import get_package_share_directory

        return get_package_share_directory(package)
    except Exception:
        return None


def _resolve(explicit: str, package: str, relative: str) -> str:
    here = os.path.dirname(os.path.abspath(__file__))
    candidates: List[str] = []
    if explicit:
        candidates.append(os.path.expanduser(explicit))
    share = _share_dir(package)
    if share:
        candidates.append(os.path.join(share, relative))
    candidates.append(os.path.join(here, "..", "..", package, relative))
    for candidate in candidates:
        if os.path.isfile(candidate):
            return os.path.normpath(candidate)
    raise DatasetConfigError(
        f"cannot locate {package}/{relative} (searched: {', '.join(candidates)})"
    )


def resolve_arena_config_path(explicit: str = "") -> str:
    """The base ``arena.yaml`` (explicit > installed cat_arena > source tree)."""
    return _resolve(explicit, "cat_arena", os.path.join("config", "arena.yaml"))


def resolve_rover_config_path(explicit: str = "") -> str:
    """The base ``rover.yaml`` (explicit > installed rover_description > source tree)."""
    return _resolve(explicit, "rover_description", os.path.join("config", "rover.yaml"))


