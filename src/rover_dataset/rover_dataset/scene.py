def _sun_direction(elevation_deg: float, azimuth_deg: float) -> Tuple[float, float, float]:
    """Light travel direction for a sun at ``elevation``/``azimuth``.

    Azimuth 0 puts the sun in the ``+x`` (east) half; the returned vector points
    *down* (``z < 0``) because it is the direction the light travels.
    """
    elev = math.radians(elevation_deg)
    az = math.radians(azimuth_deg)
    vec = (-math.cos(elev) * math.cos(az), -math.cos(elev) * math.sin(az), -math.sin(elev))
    norm = math.sqrt(sum(v * v for v in vec)) or 1.0
    return (vec[0] / norm, vec[1] / norm, vec[2] / norm)


def _shift_rgb(rgb: Tuple[float, float, float], hue_shift: float, value_scale: float) -> Tuple[float, float, float]:
    r, g, b = rgb
    h, s, v = colorsys.rgb_to_hsv(r, g, b)
    h = (h + hue_shift) % 1.0
    v = min(1.0, max(0.0, v * value_scale))
    return tuple(round(c, 6) for c in colorsys.hsv_to_rgb(h, s, v))  # type: ignore[return-value]


def _clamp01(value: float) -> float:
    return min(1.0, max(0.0, value))


def _sample_arena_overrides(
    base: Dict[str, Any], rand: SceneRandomization, rng: Any
) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    """Mutate a copy of the base arena.yaml and record what was sampled."""
    arena = json.loads(json.dumps(base))  # deep copy of plain YAML data

    sand = arena.setdefault("arena", {}).get("sand_color", [0.84, 0.78, 0.58, 1.0])
    hue_shift = rand.sand_hue_shift.sample(rng)
    value_scale = rand.sand_value_scale.sample(rng)
    new_sand = _shift_rgb((float(sand[0]), float(sand[1]), float(sand[2])), hue_shift, value_scale)
    arena["arena"]["sand_color"] = [new_sand[0], new_sand[1], new_sand[2], 1.0]

    terrain = arena.setdefault("terrain", {})
    noise_amplitude = rand.terrain_noise_amplitude.sample(rng)
    terrain["noise_amplitude"] = round(noise_amplitude, 6)

    elevation = rand.sun_elevation_deg.sample(rng)
    azimuth = rand.sun_azimuth_deg.sample(rng)
    warm_cool = rand.sun_warm_cool.sample(rng)
    intensity = rand.sun_intensity_scale.sample(rng)
    cast_shadows = bool(rng.random() < rand.sun_cast_shadows_prob)
    direction = _sun_direction(elevation, azimuth)

    light = arena.setdefault("light", {})
    base_diffuse = light.get("diffuse", [0.92, 0.90, 0.86, 1.0])
    diffuse = [
        _clamp01(float(base_diffuse[0]) * (1.0 + warm_cool) * intensity),
        _clamp01(float(base_diffuse[1]) * intensity),
        _clamp01(float(base_diffuse[2]) * (1.0 - warm_cool) * intensity),
        1.0,
    ]
    light["direction"] = [round(v, 6) for v in direction]
    light["diffuse"] = [round(v, 6) for v in diffuse]
    light["cast_shadows"] = cast_shadows

    ambient_value = rand.ambient.sample(rng)
    background_value = rand.background.sample(rng)
    scene = arena.setdefault("scene", {})
    scene["ambient"] = [round(ambient_value, 6)] * 3 + [1.0]
    base_background = scene.get("background", [0.72, 0.80, 0.90, 1.0])
    ratios = (
        float(base_background[0]) / max(1e-6, float(base_background[2])),
        float(base_background[1]) / max(1e-6, float(base_background[2])),
    )
    scene["background"] = [
        round(_clamp01(background_value * ratios[0]), 6),
        round(_clamp01(background_value * ratios[1]), 6),
        round(_clamp01(background_value), 6),
        1.0,
    ]
    scene["shadows"] = cast_shadows

    params = {
        "sand_color": [new_sand[0], new_sand[1], new_sand[2]],
        "sand_hue_shift": hue_shift,
        "sand_value_scale": value_scale,
        "terrain_noise_amplitude": noise_amplitude,
        "sun_elevation_deg": elevation,
        "sun_azimuth_deg": azimuth,
        "sun_warm_cool": warm_cool,
        "sun_intensity_scale": intensity,
        "sun_cast_shadows": cast_shadows,
        "sun_direction": list(direction),
        "ambient": ambient_value,
        "background": background_value,
    }
    return arena, params


def _sample_rover_overrides(
    base: Dict[str, Any], rand: SceneRandomization, rng: Any
) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    """Jitter every camera mount in a copy of the base rover.yaml."""
    rover = json.loads(json.dumps(base))
    max_t = rand.mount_translation_m.sample(rng)
    max_r = rand.mount_rotation_deg.sample(rng)
    record: Dict[str, Any] = {"translation_m": max_t, "rotation_deg": max_r, "cameras": {}}
    for camera in rover.get("sensors", {}).get("cameras", []):
        # random direction on the unit sphere (the *magnitude* is uniform in
        # [0, max_t]); rpy jitter is independent per axis
        dirs = [rng.gauss(0.0, 1.0) for _ in range(3)]
        norm = math.sqrt(sum(d * d for d in dirs)) or 1.0
        dist = rng.uniform(0.0, max_t)
        delta = [d / norm * dist for d in dirs]
        origin = list(camera.get("origin", [0.0, 0.0, 0.0]))
        camera["origin"] = [round(float(origin[i]) + delta[i], 6) for i in range(3)]
        rpy = list(camera.get("rpy_deg", [0.0, 0.0, 0.0]))
        d_rpy = [rng.uniform(-max_r, max_r) for _ in range(3)]
        camera["rpy_deg"] = [round(float(rpy[i]) + d_rpy[i], 6) for i in range(3)]
        record["cameras"][str(camera.get("name", "?"))] = {
            "origin_delta": [round(v, 6) for v in delta],
            "rpy_delta_deg": [round(v, 6) for v in d_rpy],
        }
    return rover, record


def scene_specs(
    cfg: DatasetConfig,
    master_seed: Optional[int] = None,
    count: Optional[int] = None,
) -> List[SceneSpec]:
    """Deterministic list of scene specifications (no files written)."""
    seed = cfg.scene.start_seed if master_seed is None else int(master_seed)
    n = cfg.scene.count if count is None else int(count)
    arena_base = _load_yaml(resolve_arena_config_path(cfg.paths.arena_config))
    rover_base = _load_yaml(resolve_rover_config_path(cfg.paths.rover_config))

    specs: List[SceneSpec] = []
    for index in range(n):
        rng = rng_python(seed, cfg.scene.seed_namespace, index)
        arena_yaml, arena_params = _sample_arena_overrides(arena_base, cfg.scene, rng)
        rover_yaml, rover_params = _sample_rover_overrides(rover_base, cfg.scene, rng)
        arena_seed = derive_seed(seed, f"{cfg.scene.seed_namespace}:arena", index) % (2 ** 31 - 1)
        params = dict(arena_params)
        params["camera_mount_jitter"] = rover_params
        params["arena_seed"] = arena_seed
        specs.append(
            SceneSpec(
                index=index,
                scene_id=f"sim_{index:04d}",
                source="sim",
                seed=arena_seed,
                arena_yaml=arena_yaml,
                rover_yaml=rover_yaml,
                params=params,
            )
        )
    return specs


def _load_yaml(path: str) -> Dict[str, Any]:
    import yaml

    if not os.path.isfile(path):
        raise DatasetConfigError(f"config not found: {path}")
    with open(path, "r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise DatasetConfigError(f"{path}: expected a mapping at the top level")
    return data


def _dump_yaml(data: Dict[str, Any], path: str) -> None:
    import yaml

    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("# generated by rover_dataset.scene -- do not edit\n")
        yaml.safe_dump(data, handle, sort_keys=False, default_flow_style=False)


def _sha256_file(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_scene_files(spec: SceneSpec, scenes_dir: str) -> SceneFiles:
    """Write ``arena.yaml``, ``rover.yaml`` and ``scene.json`` for one scene."""
    directory = os.path.join(scenes_dir, spec.scene_id)
    os.makedirs(directory, exist_ok=True)
    arena_path = os.path.join(directory, "arena.yaml")
    rover_path = os.path.join(directory, "rover.yaml")
    record_path = os.path.join(directory, "scene.json")
    _dump_yaml(spec.arena_yaml, arena_path)
    _dump_yaml(spec.rover_yaml, rover_path)

    record = spec.as_dict()
    record["dataset_config_sha256"] = None
    record["files"] = {
        "arena.yaml": _sha256_file(arena_path),
        "rover.yaml": _sha256_file(rover_path),
    }
    with open(record_path, "w", encoding="utf-8") as handle:
        json.dump(record, handle, indent=1, sort_keys=True)
        handle.write("\n")
    return SceneFiles(spec.scene_id, directory, arena_path, rover_path, record_path)


def scenes_index_path(scenes_dir: str) -> str:
    return os.path.join(scenes_dir, _SCENES_INDEX)


def prepare_scenes(
    cfg: DatasetConfig,
    master_seed: Optional[int] = None,
    count: Optional[int] = None,
) -> Tuple[List[SceneSpec], List[SceneFiles]]:
    """Build every scene spec and write its config files + index."""
    specs = scene_specs(cfg, master_seed=master_seed, count=count)
    scenes_dir = cfg.paths.scenes_dir
    files = [write_scene_files(spec, scenes_dir) for spec in specs]
    index = {
        "schema_version": 1,
        "dataset_config_sha256": cfg.config_sha256(),
        "master_seed": cfg.scene.start_seed if master_seed is None else int(master_seed),
        "count": len(specs),
        "scenes": [spec.as_dict() for spec in specs],
    }
    os.makedirs(scenes_dir, exist_ok=True)
    with open(scenes_index_path(scenes_dir), "w", encoding="utf-8") as handle:
        json.dump(index, handle, indent=1, sort_keys=True)
        handle.write("\n")
    return specs, files


def load_scenes_index(scenes_dir: str) -> Dict[str, Any]:
    path = scenes_index_path(scenes_dir)
    if not os.path.isfile(path):
        raise DatasetConfigError(f"scene index not found: {path}")
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)
