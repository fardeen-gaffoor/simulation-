_SCENES_INDEX = "scenes.json"


@dataclass
class SceneSpec:
    """One scene's complete, reproducible randomization record."""

    index: int
    scene_id: str
    source: str
    seed: int
    arena_yaml: Dict[str, Any]
    rover_yaml: Dict[str, Any]
    params: Dict[str, Any] = field(default_factory=dict)

    def as_dict(self) -> Dict[str, Any]:
        return {
            "scene_id": self.scene_id,
            "index": self.index,
            "source": self.source,
            "seed": self.seed,
            "params": self.params,
        }


@dataclass
class SceneFiles:
    scene_id: str
    directory: str
    arena_config: str
    rover_config: str
    record: str

    def as_dict(self) -> Dict[str, Any]:
        return {
            "scene_id": self.scene_id,
            "directory": self.directory,
            "arena_config": self.arena_config,
            "rover_config": self.rover_config,
            "record": self.record,
        }


